export function tTemplate(key, language = "en", variables = {}) {
    const lang = language === "it" ? "it" : "en";
    const dict = TEMPLATE_MESSAGES[lang] || TEMPLATE_MESSAGES.en;
    let text = dict[key] || TEMPLATE_MESSAGES.en[key] || key;
    for (const [varKey, varVal] of Object.entries(variables)) {
        text = text.replace(new RegExp(`\\{${varKey}\\}`, "g"), String(varVal));
    }
    return text;
}
