export function tReference(key, language = "en", variables = {}) {
    const lang = language === "it" ? "it" : "en";
    const dict = REFERENCE_MESSAGES[lang] || REFERENCE_MESSAGES.en;
    let text = dict[key] || REFERENCE_MESSAGES.en[key] || key;
    for (const [varKey, varVal] of Object.entries(variables)) {
        text = text.replace(new RegExp(`\\{${varKey}\\}`, "g"), String(varVal));
    }
    return text;
}
